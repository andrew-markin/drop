#!/usr/bin/env python3
# Writes protocol.json: the expected values of every step of docs/PROTOCOL.md for fixed inputs.
# PyNaCl (python3-nacl) is a third implementation, so the desktop and the web code are both checked
# against it rather than against each other. Run it again only when the protocol changes.

import base64
import json
import pathlib

import nacl.bindings as sodium
import nacl.hashlib


def b64(data):
    return base64.urlsafe_b64encode(data).decode().rstrip('=')


def pattern(seed, size):
    return bytes((seed + 37 * i) % 256 for i in range(size))


def keyed_blake2b(key, message, size):
    return nacl.hashlib.blake2b(message, digest_size=size, key=key).digest()


def seal(key, nonce, plaintext, ad):
    return nonce + sodium.crypto_aead_xchacha20poly1305_ietf_encrypt(plaintext, ad, nonce, key)


k = pattern(1, 32)
cs = pattern(2, 32)
ss = pattern(3, 32)
sid = pattern(4, 16)

cp = sodium.crypto_scalarmult_base(cs)
sp = sodium.crypto_scalarmult_base(ss)

hello = keyed_blake2b(k, b'Drop/1 hello' + cp, 32)

shared = sodium.crypto_scalarmult(cs, sp)
assert shared == sodium.crypto_scalarmult(ss, cp)

keys = keyed_blake2b(k, b'Drop/1 keys' + shared + cp + sp, 64)
up, down = keys[:32], keys[32:]

confirm_nonce = pattern(5, 24)
confirm = seal(down, confirm_nonce, b'', b'Drop/1 confirm' + sid + cp + sp)

path = '/api/session/' + b64(sid) + '/file'
request_plaintext = json.dumps(
    {'name': 'IMG_0042.jpg', 'size': 3145728, 'modified': 1761580800000, 'head': b64(pattern(6, 32))},
    separators=(',', ':'),
).encode()
request_nonce = pattern(7, 24)
request = seal(up, request_nonce, request_plaintext, b'Drop/1 request' + sid + b'POST ' + path.encode())

answer_plaintext = json.dumps({'file': b64(pattern(8, 16)), 'chunk': 4194304, 'received': []},
                              separators=(',', ':')).encode()
answer_nonce = pattern(9, 24)
answer = seal(down, answer_nonce, answer_plaintext, b'Drop/1 answer' + request_nonce)

vectors = {
    'comment': 'Generated by generate.py, all binary values are base64url without padding',
    'inputs': {
        'k': b64(k),
        'clientSecretKey': b64(cs),
        'serverSecretKey': b64(ss),
        'session': b64(sid),
        'confirmNonce': b64(confirm_nonce),
        'requestNonce': b64(request_nonce),
        'answerNonce': b64(answer_nonce),
    },
    'link': 'http://192.168.0.5:54246/#k=' + b64(k),
    'clientPublicKey': b64(cp),
    'serverPublicKey': b64(sp),
    'hello': b64(hello),
    'shared': b64(shared),
    'up': b64(up),
    'down': b64(down),
    'confirm': b64(confirm),
    'request': {
        'method': 'POST',
        'path': path,
        'plaintext': request_plaintext.decode(),
        'sealed': b64(request),
    },
    'answer': {
        'plaintext': answer_plaintext.decode(),
        'sealed': b64(answer),
    },
    # A low-order point: X25519 with it gives all zeros, both sides must refuse it
    'lowOrderPublicKey': b64(bytes(32)),
}

path = pathlib.Path(__file__).with_name('protocol.json')
path.write_text(json.dumps(vectors, indent=2, ensure_ascii=False) + '\n')
